// ВОРКЕР КОРНЯ — САМОЛИКВИДАТОР. Раньше в корне сайта жила BBG Block со
// своим сервис-воркером (область — весь сайт). Теперь в корне страница
// игр, а BBG Block — в block/ со своим воркером. Браузер тех, кто уже
// открывал игру, при следующем заходе найдёт этот новый sw.js, поставит
// его — и он тут же снимет себя: корень больше не кэшируется, страница
// игр всегда свежая. Старый кэш «bbg-…» удалит воркер BBG Block в block/
// при своей активации (он чистит все «bbg-…», кроме своего).
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(self.registration.unregister()));
